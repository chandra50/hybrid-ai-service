"""Render docs/hybrid-ai-brief.pdf into page images for the dashboard's Presentation tab.

    python tools/build_presentation.py   ->  dashboard/presentation/{slide-N.jpg, hybrid-ai-brief.pdf, slides.js}

Needs pdftoppm (poppler-utils) and python-pptx (for the slide titles). Rebuild after
regenerating the brief PDF.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

from pptx import Presentation

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "docs" / "hybrid-ai-brief.pdf"
PPTX = ROOT / "docs" / "hybrid-ai-brief.pptx"
OUT = ROOT / "dashboard" / "presentation"


def main() -> None:
    titles = [s.shapes.title.text_frame.text if s.shapes.title else f"Slide {i}"
              for i, s in enumerate(Presentation(str(PPTX)).slides, start=1)]
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("slide-*.jpg"):
        old.unlink()
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["pdftoppm", "-r", "110", "-jpeg", "-jpegopt", "quality=82", str(PDF), f"{tmp}/p"], check=True)
        pages = sorted(Path(tmp).glob("p-*.jpg"), key=lambda p: int(p.stem.split("-")[1]))
        for i, p in enumerate(pages, start=1):
            shutil.move(p, OUT / f"slide-{i}.jpg")
    if len(pages) != len(titles):
        raise SystemExit(f"{PDF.name} has {len(pages)} pages but {PPTX.name} has {len(titles)} slides: rebuild the PDF")
    shutil.copy2(PDF, OUT / PDF.name)
    manifest = {"title": "Keeping remote compressors running", "pdf": f"presentation/{PDF.name}",
                "slides": [{"src": f"presentation/slide-{i}.jpg", "title": t} for i, t in enumerate(titles, start=1)]}
    (OUT / "slides.js").write_text("// generated by tools/build_presentation.py\nwindow.PRESENTATION = "
                                   + json.dumps(manifest, indent=1) + ";\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(pages)} slides, " + f"{sum(f.stat().st_size for f in OUT.iterdir()) // 1024} KB")


if __name__ == "__main__":
    main()
